# 5. Model Architecture: CNN-Transformer with "Early Exit" (The Latency Fix)

class DeepfakeDetector(nn.Module):
    def __init__(self, num_classes=2):
        super().__init__()

        # Stage 1: Lightweight CNN (Feature Extractor)
        # Input: (Batch, 2 channels, 64 freq, Time)
        self.cnn = nn.Sequential(
            nn.Conv2d(2, 16, kernel_size=3, padding=1),
            nn.BatchNorm2d(16),
            nn.ReLU(),
            nn.MaxPool2d(2, 2), # -> (16, 32, Time/2)

            nn.Conv2d(16, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2, 2), # -> (32, 16, Time/4)

            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2, 2)  # -> (64, 8, Time/8)
        )

        # Compute dimension after CNN
        # For a 200ms chunk (approx 3200 samples -> ~20 frames mel)
        # Time dim reduces: 20 -> 10 -> 5 -> 2

        # Stage 2: Early Exit (Latency < 50ms)
        self.early_exit_gap = nn.AdaptiveAvgPool2d(1)
        self.early_exit_head = nn.Linear(64, 1) # Binary regression (0-1)

        # Stage 3: Transformer (Context Aggregator)
        self.projection = nn.Linear(64 * 8, 128) # Flatten freq dimension
        encoder_layer = nn.TransformerEncoderLayer(d_model=128, nhead=4, dim_feedforward=256, batch_first=True)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=2)

        # Stage 4: Final Head (Stable Decision)
        self.final_head = nn.Sequential(
            nn.Linear(128, 64),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(64, 1) # Binary regression (0-1)
        )

    def forward(self, x):
        # x: (Batch, 2, 64, Time)

        # 1. CNN Features
        features_2d = self.cnn(x) # (Batch, 64, 8, Reduced_Time)

        # 2. Early Exit Path
        # Global Average Pooling for instant snapshot
        pooled_early = self.early_exit_gap(features_2d).flatten(1)
        early_score = torch.sigmoid(self.early_exit_head(pooled_early))

        # 3. Transformer Prep
        # Permute to (Batch, Time, Channels*Freq)
        batch, ch, freq, time = features_2d.shape
        features_seq = features_2d.permute(0, 3, 1, 2).reshape(batch, time, ch * freq)

        # Project to d_model
        projected = self.projection(features_seq)

        # 4. Transformer Context features
        context_features = self.transformer(projected)

        # Pool over time for final decision (take mean of sequence)
        context_pooled = context_features.mean(dim=1)

        # 5. Final Decision
        final_score = torch.sigmoid(self.final_head(context_pooled))

        return early_score, final_score

