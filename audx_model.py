# 6. Post-Processing UX Logic (The "Anti-Flicker" Fix)

class StableDecisionMaker:
    """
    Prevents UI flickering by using hysteresis and smoothing.
    """
    def __init__(self, history_len=5, high_threshold=0.85, low_threshold=0.60):
        self.history = deque(maxlen=history_len)
        self.high_threshold = high_threshold
        self.low_threshold = low_threshold
        self.current_state = "SAFE" # SAFE or THREAT

    def update(self, new_score):
        # 1. Add to rolling window
        self.history.append(new_score)

        # 2. Median Filter (Smooth out outliers)
        smoothed_score = np.median(self.history)

        # 3. Hysteresis Logic
        if self.current_state == "SAFE":
            if smoothed_score > self.high_threshold:
                self.current_state = "THREAT"
        else: # Currently in THREAT state
            if smoothed_score < self.low_threshold:
                self.current_state = "SAFE"

        return self.current_state, smoothed_score

