# 3. Robust Preprocessing (The "False Positive" Fix)

class AudioPreprocessor:
    """
    Cleans audio stream and filters out silence/non-speech to prevent false positives
    triggered by background noise (e.g., car horns, typing).
    """
    def __init__(self, sample_rate=16000, vad_threshold_db=20):
        self.sample_rate = sample_rate
        self.vad_threshold_db = vad_threshold_db

    def suppress_noise(self, audio_numpy):
        """
        Uses spectral gating to remove stationary noise.
        Input: numpy array (C, T) or (T,)
        """
        # noisereduce expects (C, T) or (T,)
        # For simple streaming, we assume stationary noise profile estimated from first few frames
        # Here we use a fast stationary approximation
        try:
            cleaned = nr.reduce_noise(y=audio_numpy, sr=self.sample_rate, stationary=True, prop_decrease=0.75)
            return cleaned
        except Exception as e:
            # Fallback if noise reduction fails (e.g. too short)
            return audio_numpy

    def is_speech_active(self, waveform):
        """
        Simple Energy-based VAD.
        Returns True if RMS energy > threshold.
        """
        # Convert to DB
        rms = torch.sqrt(torch.mean(waveform ** 2))
        db = 20 * torch.log10(rms + 1e-9)

        # Threshold check (relative to full scale or calibrated background)
        # In normalized wav (-1 to 1), -40dB is a reasonable silence floor
        return db > -40.0 # Strict check, adjustable

    def process(self, waveform):
        """
        Full pipeline: Tensor -> Numpy -> Denoise -> Tensor -> VAD Check
        Result: (processed_waveform, is_active)
        """
        # 1. Convert to numpy for noisereduce library
        wav_np = waveform.cpu().numpy()

        # 2. Denoise
        if len(wav_np.shape) > 1:
            wav_np = wav_np[0] # Take first channel for mono proc

        clean_np = self.suppress_noise(wav_np)
        clean_tensor = torch.from_numpy(clean_np).unsqueeze(0).to(waveform.device).float()

        # 3. VAD
        is_active = self.is_speech_active(clean_tensor)

        return clean_tensor, is_active

