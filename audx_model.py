def train_audionyx(model, train_loader, val_loader, epochs=10, lr=1e-4, patience=3):
    """
    Training loop with Early Stopping:
    - Saves 'audionyx_model.pt' whenever validation loss improves.
    - AUTOMATICALLY restores the best weights at the end of training.
    """
    criterion = nn.BCELoss() # Binary Cross Entropy
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)

    # Weights for the loss: Prioritize accuracy of the final transformer head
    loss_weight_early = 0.4
    loss_weight_final = 1.0

    # Early Stopping Variables
    best_val_loss = float('inf')
    patience_counter = 0
    best_model_path = "audionyx_model.pt"

    for epoch in range(epochs):
        model.train()
        total_loss = 0
        correct_final = 0
        total_samples = 0

        print(f"\nEpoch {epoch+1}/{epochs}")
        print("-" * 20)

        for batch_idx, (waveform, label) in enumerate(train_loader):
            waveform, label = waveform.to(device), label.to(device)
            if waveform.dim() == 2: waveform = waveform.unsqueeze(1)

            features = feature_extractor(waveform.squeeze(1))
            early_prob, final_prob = model(features)

            loss_early = criterion(early_prob, label)
            loss_final = criterion(final_prob, label)
            loss = (loss_weight_early * loss_early) + (loss_weight_final * loss_final)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            total_loss += loss.item()
            preds = (final_prob > 0.5).float()
            correct_final += (preds == label).sum().item()
            total_samples += label.size(0)

            if batch_idx % 50 == 0:
                print(f"Batch {batch_idx}: Loss {loss.item():.4f}")

        avg_train_loss = total_loss / len(train_loader)
        train_acc = correct_final / total_samples
        print(f"Train Loss: {avg_train_loss:.4f} | Train Acc: {train_acc*100:.2f}%")

        # Validation & Early Stopping Check
        if val_loader:
            val_loss, val_acc = validate(model, val_loader, criterion)

            if val_loss < best_val_loss:
                print(f"✅ Validation improved ({best_val_loss:.4f} -> {val_loss:.4f}). Saving model...")
                best_val_loss = val_loss
                patience_counter = 0
                torch.save(model.state_dict(), best_model_path)
            else:
                patience_counter += 1
                print(f"⚠️ No improvement. Patience: {patience_counter}/{patience}")

            if patience_counter >= patience:
                print(f"🛑 Early Stopping Triggered! Stopping now.")
                break

    # Always ensure the model in memory matches the best saved file
    print(f"\nTraining Complete. Reloading best weights from '{best_model_path}'...")
    model.load_state_dict(torch.load(best_model_path))

def validate(model, loader, criterion):
    model.eval()
    val_loss = 0
    correct = 0
    total = 0

    with torch.no_grad():
        for waveform, label in loader:
            waveform, label = waveform.to(device), label.to(device)
            features = feature_extractor(waveform.squeeze(1))
            _, final_prob = model(features)

            loss = criterion(final_prob, label)
            val_loss += loss.item()
            preds = (final_prob > 0.5).float()
            correct += (preds == label).sum().item()
            total += label.size(0)

    avg_loss = val_loss / len(loader)
    acc = correct / total
    print(f"Val Loss: {avg_loss:.4f} | Val Acc: {acc*100:.2f}%")
    return avg_loss, acc

