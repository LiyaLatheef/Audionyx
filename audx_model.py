class DeepfakeDataset(Dataset):
    def __init__(self, root_dir, max_samples=None, transform=None, target_sample_rate=16000, duration_sec=4):
        """
        Args:
            root_dir (str): Path to dataset root containing 'real' and 'fake' subfolders.
            max_samples (int): Limit number of files for quick debugging.
            transform (callable): Augmentation function (TelephonyAugment).
            duration_sec (int): Fixed duration to pad/truncate audio to.
        """
        self.root_dir = root_dir
        self.transform = transform
        self.target_sample_rate = target_sample_rate
        self.num_samples = int(target_sample_rate * duration_sec)

        # Load file paths
        self.real_files = glob.glob(os.path.join(root_dir, 'real', '*.*'))
        self.fake_files = glob.glob(os.path.join(root_dir, 'fake', '*.*'))

        if max_samples:
            self.real_files = self.real_files[:max_samples]
            self.fake_files = self.fake_files[:max_samples]

        # Create (filepath, label) tuples. Label: 0=Real, 1=Fake (standard convention)
        self.file_list = [(f, 0.0) for f in self.real_files] + [(f, 1.0) for f in self.fake_files]
        random.shuffle(self.file_list)

        print(f"Found {len(self.real_files)} Real and {len(self.fake_files)} Fake samples.")

    def __len__(self):
        return len(self.file_list)

    def __getitem__(self, idx):
        filepath, label = self.file_list[idx]

        try:
            # Robust Audio Loading
            # Problem: Some files trigger "TorchCodec" errors or are encoded strangely.
            # Solution: Try native torchaudio, fallback to librosa (FFmpeg-based).
            try:
                waveform, sr = torchaudio.load(filepath)
            except Exception:
                # Fallback: using librosa which is more robust to format issues
                y, sr = librosa.load(filepath, sr=None, mono=False)

                # Ensure shape is (Channels, Time)
                if y.ndim == 1:
                    y = y[np.newaxis, :]

                waveform = torch.from_numpy(y).float()

            # Resample if needed
            if sr != self.target_sample_rate:
                resampler = T.Resample(sr, self.target_sample_rate)
                waveform = resampler(waveform)

            # Mix to mono
            if waveform.shape[0] > 1:
                waveform = torch.mean(waveform, dim=0, keepdim=True)

            # Pad or Truncate to fixed length
            if waveform.shape[1] < self.num_samples:
                # Pad
                padding = self.num_samples - waveform.shape[1]
                waveform = F.pad(waveform, (0, padding))
            else:
                # Random Crop
                start = random.randint(0, waveform.shape[1] - self.num_samples)
                waveform = waveform[:, start:start+self.num_samples]

            # Apply Augmentation (Telephony Effects)
            if self.transform:
                waveform = self.transform(waveform)

            return waveform, torch.tensor([label], dtype=torch.float32)

        except Exception as e:
            # Only print error if it's NOT the common load error we just handled
            print(f"Failed to load {os.path.basename(filepath)}: {e}")
            # Return a generic silence tensor to prevent crashing
            return torch.zeros((1, self.num_samples)), torch.tensor([label], dtype=torch.float32)

