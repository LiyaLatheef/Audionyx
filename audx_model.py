# 8.1 Detailed Performance Evaluation
import time
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    confusion_matrix, roc_auc_score, roc_curve, ConfusionMatrixDisplay
)
import matplotlib.pyplot as plt

def evaluate_performance(model, loader, device):
    model.eval()
    y_true = []
    y_pred = []
    y_scores = []
    latencies = []

    print("running comprehensive evaluation...")

    with torch.no_grad():
        for waveform, label in loader:
            waveform = waveform.to(device)
            # Ensure proper dimensions (Batch, Channel, Time)
            if waveform.dim() == 2: waveform = waveform.unsqueeze(1)

            # Start timer for latency
            start_time = time.time()

            # Forward pass
            features = feature_extractor(waveform.squeeze(1))
            _, final_prob = model(features)

            # End timer
            end_time = time.time()

            # Record latency (ms) per batch - divided by batch size for per-sample estimate
            batch_size = waveform.size(0)
            latencies.append((end_time - start_time) * 1000 / batch_size)

            # Store results
            y_true.extend(label.cpu().numpy().flatten())
            y_scores.extend(final_prob.cpu().numpy().flatten())
            y_pred.extend((final_prob > 0.5).cpu().numpy().flatten().astype(int))

    # Metric Calculations
    acc = accuracy_score(y_true, y_pred)
    prec = precision_score(y_true, y_pred)
    rec = recall_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred)

    try:
        auc = roc_auc_score(y_true, y_scores)

        # EER Calculation
        fpr, tpr, thresholds = roc_curve(y_true, y_scores)
        fnr = 1 - tpr
        # EER is where FPR crosses FNR
        eer_threshold = thresholds[np.nanargmin(np.absolute((fnr - fpr)))]
        eer = fpr[np.nanargmin(np.absolute((fnr - fpr)))]
    except ValueError:
        auc = 0.5
        eer = 0.5
        eer_threshold = 0.5
        print("⚠️ Warning: Could not calculate ROC/EER (likely only one class present in subset)")

    avg_latency = np.mean(latencies)

    # Report
    print("\n" + "="*40)
    print("🔍 MODEL PERFORMANCE REPORT")
    print("="*40)
    print(f"✅ Accuracy:          {acc:.4f} ({acc*100:.2f}%)")
    print(f"🎯 Precision:         {prec:.4f}")
    print(f"🕵️ Recall:            {rec:.4f}")
    print(f"⚖️ F1-Score:          {f1:.4f}")
    print(f"📈 ROC-AUC:           {auc:.4f}")
    print(f"⚙️ EER (Equal Error): {eer:.4f} (Threshold: {eer_threshold:.4f})")
    print(f"⚡ Avg Latency:       {avg_latency:.2f} ms/sample")
    print("="*40)

    # Visualization: Confusion Matrix
    cm = confusion_matrix(y_true, y_pred)
    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=["Real", "Deepfake"])

    fig, ax = plt.subplots(1, 2, figsize=(12, 5))

    # Plot Confusion Matrix
    disp.plot(ax=ax[0], cmap='Blues', values_format='d')
    ax[0].set_title("Confusion Matrix")

    # Plot ROC Curve
    if 'fpr' in locals():
        ax[1].plot(fpr, tpr, label=f"AUC = {auc:.2f}")
        ax[1].plot([0, 1], [0, 1], 'k--')
        ax[1].set_xlabel("False Positive Rate")
        ax[1].set_ylabel("True Positive Rate")
        ax[1].set_title("ROC Curve")
        ax[1].legend()

    plt.tight_layout()
    plt.show()

# Run evaluation on Validation Set
