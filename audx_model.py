# 2. Telephony-Specific Data Augmentation (The "Domain Gap" Fix)

class TelephonyAugment:
    """
    Simulates 'In-The-Wild' phone call conditions to bridge the domain gap between
    clean training data and real-world VoIP/GSM audio.
    """
    def __init__(self, sample_rate=16000):
        self.sample_rate = sample_rate
        # Standard telephony bandpass
        self.low_freq = 300
        self.high_freq = 3400

    def apply_narrowband(self, waveform):
        """Applies 300Hz-3400Hz Bandpass Filter"""
        return AF.bandpass_biquad(waveform, self.sample_rate, central_freq=1850, Q=0.6)

    def apply_codec_simulation(self, waveform):
        """
        Simulates GSM/AMR quality by downsampling to 8kHz and upsampling back.
        This creates the aliasing and high-frequency loss typical of phone lines.
        """
        downsampler = T.Resample(self.sample_rate, 8000).to(waveform.device)
        upsampler = T.Resample(8000, self.sample_rate).to(waveform.device)

        downsampled = downsampler(waveform)
        restored = upsampler(downsampled)
        return restored

    def inject_noise(self, waveform, noise_level=0.005):
        """Injects random Gaussian noise (simulating line static)"""
        noise = torch.randn_like(waveform) * noise_level
        return waveform + noise

    def __call__(self, waveform):
        # 1. Bandpass (Narrowband)
        aug_wav = self.apply_narrowband(waveform)

        # 2. Codec Simulation (GSM-like)
        aug_wav = self.apply_codec_simulation(aug_wav)

        # 3. Noise Injection
        if random.random() > 0.5:
             aug_wav = self.inject_noise(aug_wav)

        return aug_wav

