class HybridFeatureExtractor(nn.Module):
    """
    Extracts and stacks Mel-Spectrograms (spatial/timbre) and LFCCs (phase/voice characteristics).
    Optimized for short streaming windows.
    """
    def __init__(self, sample_rate=16000, n_mels=64, n_lfcc=64):
        super().__init__()
        self.mel_transform = T.MelSpectrogram(
            sample_rate=sample_rate,
            n_mels=n_mels,
            n_fft=400,
            win_length=400,
            hop_length=160
        )

        # Fixed: LFCC expects STFT kwargs in a dictionary named 'speckwargs'
        self.lfcc_transform = T.LFCC(
            sample_rate=sample_rate,
            n_lfcc=n_lfcc,
            speckwargs={
                "n_fft": 400,
                "win_length": 400,
                "hop_length": 160
            }
        )

    def forward(self, waveform):
        # 1. Extract Mel-Spectrogram
        # Shape: (Batch, n_mels, Time)
        mels = self.mel_transform(waveform)
        mels = T.AmplitudeToDB()(mels) # Log scale

        # 2. Extract LFCC
        # Shape: (Batch, n_lfcc, Time)
        lfccs = self.lfcc_transform(waveform)

        # 3. Normalization (Simple instance norm for robustness)
        mels = (mels - mels.mean()) / (mels.std() + 1e-6)
        lfccs = (lfccs - lfccs.mean()) / (lfccs.std() + 1e-6)

        # 4. Stack features
        # We treat Mel and LFCC as 2 separate channels for the CNN
        # Shape: (Batch, 2, Freq_Bins, Time)
        # Note: Freq_Bins = n_mels = n_lfcc
        combined = torch.stack([mels, lfccs], dim=1)

        return combined

